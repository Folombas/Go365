// ================== ЭТАП 1: ГЕНЕРАТОР ВРЕМЕННОГО ПОТОКА ==================
func generateDatePipeline() <-chan time.Time {
	dates := make(chan time.Time)
	start := time.Date(2026, 1, 18, 0, 0, 0, 0, time.UTC) // День удаления CapCut

	go func() {
		defer close(dates)
		for d := start; !d.After(time.Now().UTC()); d = d.AddDate(0, 0, 1) {
			dates <- d
			time.Sleep(10 * time.Millisecond) // Драматическая пауза в конвейере
		}
	}()

	fmt.Println("✅ ЭТАП 1: Запущен генератор временной шкалы...")
	return dates
}

// ================== ЭТАП 2: ПОДСЧЁТ ДНЕЙ СОПРОТИВЛЕНИЯ ==================
func countResistanceDays(dates <-chan time.Time) int {
	count := 0
	fmt.Print("✅ ЭТАП 2: Подсчёт дней сопротивления [")

	for range dates {
		count++
		if count%5 == 0 {
			fmt.Print("▓") // Визуализация прогресс-бара
		}
	}
	fmt.Println("]")
	return count
}

