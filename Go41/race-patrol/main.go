package main

import (
	"fmt"
	"sync"
	"sync/atomic"
	"time"
)

// ========== ЛЕГЕНДА ДНЯ 41: ПРОМЗОНА, ПРОЕЗДНОЙ И ГОНКИ ==========
/*
	Сегодня 11 февраля 2026. Проездной истёк вчера в полночь.
	Никуда не еду — гуляю по промзоне. Снег, холодно, устроил выходной себе.
	Дома: картошка, пылесос, слайсы и горутины в курсе.
	Главное — снова не установил CapCut. День 24? 25? Сейчас посчитаем…
*/

func main() {
	// Дата великого удаления CapCut
	start := time.Date(2026, time.January, 18, 0, 0, 0, 0, time.UTC)
	days := int(time.Since(start).Hours() / 24)

	fmt.Println("❄️  ДЕНЬ 41: ПАТРУЛЬ ГОНКИ В ПРОМЗОНЕ ❄️")
	fmt.Println("==========================================")
	fmt.Printf("🗓️  Сегодня: %s\n", time.Now().Format("2006-01-02"))
	fmt.Printf("⚔️  Дней без CapCut: %d\n\n", days)

	// ===== ЭТАП 1: ГОНКА В ТРАМВАЕ (нескоординированные горутины) =====
	fmt.Println("🚊 ЭТАП 1: Трамвай — гонка за место у окна")
	var wg sync.WaitGroup
	windowCounter := 0
	for i := 0; i < 10; i++ {
		wg.Add(1)
		go func(id int) {
			defer wg.Done()
			for j := 0; j < days; j++ {
				// Критическая секция без охраны — как проездной без денег
				windowCounter++ // 🔥 ГОНКА!
			}
		}(i)
	}
	wg.Wait()
	fmt.Printf("   ➤ Мест у окна (без синхронизации): %d — должно быть %d ❌\n", windowCounter, days*10)

	// ===== ЭТАП 2: ЧИСТКА КАРТОШКИ (Mutex — нож и разделочная доска) =====
	fmt.Println("\n🥔 ЭТАП 2: Чистка картошки — только один нож!")
	var mu sync.Mutex
	potatoCounter := 0
	for i := 0; i < 10; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for j := 0; j < days; j++ {
				mu.Lock()
				potatoCounter++ // ✅ Мьютекс — порядок на кухне
				mu.Unlock()
			}
		}()
	}
	wg.Wait()
	fmt.Printf("   ➤ Очищено картофелин: %d ✅\n", potatoCounter)

	// ===== ЭТАП 3: ПЫЛЕСОС (атомарная уборка) =====
	fmt.Println("\n🧹 ЭТАП 3: Пылесос — атомарно всасываем пыль")
	var dustAtomic int32 = 0
	for i := 0; i < 10; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for j := 0; j < days; j++ {
				atomic.AddInt32(&dustAtomic, 1) // ✅ Без гонок, одной инструкцией
			}
		}()
	}
	wg.Wait()
	fmt.Printf("   ➤ Частиц пыли собрано: %d ✅\n", dustAtomic)

	// ===== ЭТАП 4: ДОСТИЖЕНИЯ И ПРОКАЧКА =====
	fmt.Println("\n🎮 ПРОКАЧКА ПЕРСОНАЖА: УРОВЕНЬ GO-СТРАЖА 🎮")
	achieves := []struct {
		name   string
		unlock bool
	}{
		{"🚦 Регулировщик гонок (обнаружил race)", days > 0},
		{"🔒 Шеф-повар Mutex", potatoCounter == days*10},
		{"⚛️ Инженер атомной пыли", dustAtomic == int32(days*10)},
		{"🧠 Слайс-мастер (изучил слайсы)", true},
		{"📦 Канальный гуру", true},
	}
	for _, a := range achieves {
		status := "❌"
		if a.unlock {
			status = "✅"
		}
		fmt.Printf("   %s %s\n", status, a.name)
	}
	fmt.Printf("\n✨ Опыт: +%d XP за каждый день без CapCut\n", days)
	fmt.Printf("💎 Всего XP: %d — уровень %d\n", days*100, days/7+1)

	// ===== 10 МОТИВАЦИОННЫХ КОДОВ =====
	fmt.Println("\n💬 10 ИСТИН GO-РАЗРАБОТЧИКА (перечитывать утром):")
	quotes := []string{
		"1. Гонка в коде хуже, чем отсутствие проездного: результат непредсказуем.",
		"2. Чистка картошки с мьютексом — медитация; без мьютекса — поножовщина.",
		"3. Пылесос работает атомарно — бери пример с него.",
		"4. Слайсы — как промзона: там много всего, но нужно знать индексы.",
		"5. CapCut подождёт, а собеседование на Go-разработчика — нет.",
		"6. Бары и клубы — это deadlock для твоей карьеры.",
		"7. Одна горутина без синхронизации порождает тысячу багов.",
		"8. Ты уже прошёл 41 уровень Go365 — впереди новые боссы.",
		"9. Детектор гонок — твой личный контролёр в метро.",
		"10. Не отвлекайся: каждый коммит приближает офис с панорамными окнами.",
	}
	for _, q := range quotes {
		fmt.Println(q)
	}

	// ===== ПОХВАЛА =====
	fmt.Printf("\n🌟 ГОША! Ты не установил CapCut %d дней.\n", days)
	fmt.Println("Сегодня ты не поехал на электричке, зато устроил ревизию коду.")
	fmt.Println("Промзона для прогулки, картошка начищена, гонки обнаружены.")
	fmt.Println("Твой навык «Синхронизация» повышен до 41 уровня!")
	fmt.Println("Так держать! Осталось 324 дня до Go-нирваны. 🧘")

	// ===== DISCLAIMER =====
	fmt.Println("\n=== ЮРИДИЧЕСКАЯ ПРОГУЛКА ===")
	fmt.Println("Все персонажи «Гошиных Daily Code Life Story» выдуманы.")
	fmt.Println("Сюжеты созданы для мотивации и метафор в учебном процессе.")
	fmt.Println("Любые совпадения с реальными людьми или событиями случайны.")
	fmt.Println("CapCut — отличный видеоредактор, но Go — твой главный монтажёр IT-карьеры.")
	fmt.Println("Каша «Геркулес» по-прежнему варится 15–25 минут.")
}
